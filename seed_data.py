def seed():
    db = SessionLocal()
    try:
        existing = {i.name for i in db.query(Ingredient.name).all()}
        new_items = []
        for row in INGREDIENTS:
            name, category, cal, prot, fat, carb, price, avail = row
            if name not in existing:
                new_items.append(Ingredient(
                    name=name, category=category,
                    calories=cal, proteins=prot, fats=fat, carbs=carb,
                    price_per_100g=price, is_available=avail,
                ))
        if new_items:
            db.add_all(new_items)
            db.commit()
            print(f"Добавлено {len(new_items)} ингредиентов.")
        else:
            print("База уже заполнена.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
